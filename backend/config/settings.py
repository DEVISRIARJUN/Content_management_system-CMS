# ==============================================================================
# DATABASE CONFIGURATION: MySQL with Automatic Failover to SQLite
# ==============================================================================
DB_ENGINE = os.getenv('DB_ENGINE', 'mysql').lower()
DB_NAME = os.getenv('DB_NAME', 'cms_db')
DB_USER = os.getenv('DB_USER', 'root')
DB_PASSWORD = os.getenv('DB_PASSWORD', '')
DB_HOST = os.getenv('DB_HOST', '127.0.0.1')
DB_PORT = os.getenv('DB_PORT', '3306')

USE_SQLITE = False

if DB_ENGINE == 'sqlite':
    USE_SQLITE = True
else:
    # Attempt MySQL connection & ensure DB exists
    try:
        conn = pymysql.connect(
            host=DB_HOST,
            user=DB_USER,
            password=DB_PASSWORD,
            port=int(DB_PORT),
            connect_timeout=2
        )
        with conn.cursor() as cursor:
            cursor.execute(f"CREATE DATABASE IF NOT EXISTS `{DB_NAME}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;")
        conn.close()
    except Exception as e:
        print(f"[*] Note: MySQL connection to '{DB_HOST}:{DB_PORT}' failed ({e}).")
        print("[*] Automatically falling back to local SQLite database so the app can start immediately.")
        USE_SQLITE = True

if USE_SQLITE:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': DB_NAME,
            'USER': DB_USER,
            'PASSWORD': DB_PASSWORD,
            'HOST': DB_HOST,
            'PORT': DB_PORT,
            'OPTIONS': {
                'charset': 'utf8mb4',
                'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
            }
        }
    }

